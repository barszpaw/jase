# Rasterizes mago1.ttf (Pawel's chosen OSD font, "Pixel Font mago1" by
# Nimble Beasts Collective, https://nimblebeastscollective.itch.io/magosfonts)
# into the proportional bitmap table JASE's OsdMenu actually compiles in.
#
# Needs mago1.ttf in the JASE project root to run (not committed -- see
# LICENSE NOTE below; the asset itself isn't ours to redistribute, place
# your own purchased copy there to regenerate).
#
# SIZE=16 is not an arbitrary choice: fontTools showed this font's glyph
# outlines snap to a 64-unit grid against a 1024-unit em (1 native pixel
# = 64/1024 em = 1/16 em) -- so size 16 is the ONE integer point size
# where FreeType's rasterizer lines up exactly with the font's own pixel
# grid. Any other size forces sub-pixel hinting that visibly breaks the
# blocky letterforms (confirmed: rendering at 8-10pt produced garbled,
# unrecognizable glyphs; 16pt and its multiples render perfectly crisp).
#
# Unlike bitluni's Font6x8 (used previously, see conv_bitluni_font.py),
# mago1 is PROPORTIONAL -- each glyph has its own pixel width (confirmed:
# 'i'=1px, 'M'=up to 8px) -- so OsdMenu's renderer needed a real per-
# glyph-width text layout instead of a fixed per-character step.
import os
from PIL import Image, ImageDraw, ImageFont

script_dir = os.path.dirname(__file__)
font_path = os.path.join(script_dir, "..", "..", "mago1.ttf")

SIZE = 16
CELL_H = 13  # ascent(11) + descent(2) at this size -- covers full ink incl. descenders
FIRST = 32
COUNT = 95   # 0x20..0x7E inclusive
MAX_W = 8    # fits one uint8_t row; only '}' (natural width 9) gets trimmed by 1px

font = ImageFont.truetype(font_path, SIZE)

glyphs = []
for code in range(FIRST, FIRST + COUNT):
    ch = chr(code)
    w = max(1, min(MAX_W, round(font.getlength(ch))))
    if ch == ' ':
        glyphs.append((w, [0] * CELL_H))
        continue
    canvas = Image.new("L", (24, CELL_H + 4), 0)
    d = ImageDraw.Draw(canvas)
    d.text((0, 0), ch, font=font, fill=255)
    px = canvas.load()
    rows = []
    for y in range(CELL_H):
        bits = 0
        for x in range(w):
            if px[x, y] > 128:
                bits |= (1 << (w - 1 - x))
        rows.append(bits)
    glyphs.append((w, rows))

lines = []
lines.append("// Auto-generated proportional bitmap font, printable ASCII 0x20-0x7E.")
lines.append("// Generated by tools/font/bake_mago_font.py -- see that script for how")
lines.append("// and why (size 16 specifically, to match the font's own pixel grid).")
lines.append("//")
lines.append('// Pixel data is "Pixel Font mago1" by Nimble Beasts Collective')
lines.append("// (https://nimblebeastscollective.itch.io/magosfonts), Pawel's own choice")
lines.append("// to replace the earlier bitluni Font6x8 (see conv_bitluni_font.py/")
lines.append("// Font6x8_bitluni.h, kept for reference, no longer used by default).")
lines.append("//")
lines.append("// LICENSE NOTE: unlike the rest of JASE (MIT, see LICENSE), this pixel")
lines.append("// data comes from a separately-licensed, separately-acquired asset --")
lines.append("// the itch.io page lists \"Creative Commons Attribution-ShareAlike 4.0\"")
lines.append("// (https://creativecommons.org/licenses/by-sa/4.0/) as the asset license")
lines.append('// (a "CC0 Public Domain" line also appears on the page, but the stricter')
lines.append("// CC-BY-SA is treated as authoritative here). Attribution: font by Nimble")
lines.append("// Beasts Collective. CC BY-SA's ShareAlike clause means THIS FILE (a font")
lines.append("// table, not the code that reads it) carries that license, not JASE's")
lines.append("// MIT one -- redistributing it has to keep this notice. The original")
lines.append("// mago1.ttf is a separately-sold asset and is NOT committed to this repo.")
lines.append("#pragma once")
lines.append("#include <cstdint>")
lines.append(f"static const int kOsdFontFirstChar = {FIRST};")
lines.append(f"static const int kOsdFontCharCount = {COUNT};")
lines.append(f"static const int kOsdFontHeight = {CELL_H};")
lines.append(f"struct OsdGlyph {{ uint8_t width; uint8_t rows[{CELL_H}]; }};")
lines.append(f"static const OsdGlyph kOsdFont[{COUNT}] = {{")
for i, (w, rows) in enumerate(glyphs):
    code = FIRST + i
    ch = chr(code)
    chDisp = {'\\': '\\\\', "'": "\\'"}.get(ch, ch)
    rowsStr = ", ".join(f"0x{b:02X}" for b in rows)
    lines.append(f"    {{ {w}, {{ {rowsStr} }} }}, // 0x{code:02X} '{chDisp}'")
lines.append("};")

out_path = os.path.join(script_dir, "..", "..", "src", "OsdFont.h")
with open(out_path, "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", len(glyphs), "glyphs to", out_path)
